#!/bin/sh
# Rebuilds the two nginx files that depend on Cloudflare's published IP ranges
# and reloads nginx only if they changed and still pass `nginx -t`.
#
#   /etc/nginx/conf.d/cloudflare-realip.conf       set_real_ip_from + CF-Connecting-IP
#   /etc/nginx/conf.d/cloudflare-origin-lock.conf  geo $from_cloudflare (the
#       ascendpeptides.my and www vhosts return 444 to anything not listed)
#
# Why it exists: the origin lock drops every peer that isn't a listed Cloudflare
# range. If Cloudflare adds a range and this list is stale, visitors routed
# through it get dropped, and real-IP logging/rate limits miss it too.
#
# Installed on ascend-vps as /usr/local/sbin/cloudflare-ips-refresh, run weekly
# from /etc/cron.d/cloudflare-ips-refresh, logging to /var/log/cloudflare-ips-refresh.log.
set -eu

REALIP=/etc/nginx/conf.d/cloudflare-realip.conf
LOCK=/etc/nginx/conf.d/cloudflare-origin-lock.conf
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# Cloudflare serves these without a trailing newline: echo after each, or the
# last IPv4 range and the first IPv6 range fuse into one invalid line.
{ curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4; echo; } > "$TMP/v4"
{ curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6; echo; } > "$TMP/v6"
sed -i '/^[[:space:]]*$/d' "$TMP/v4" "$TMP/v6"

# Refuse anything that isn't a plain list of CIDRs of a plausible length — an
# error page or an empty answer must never become the allow-list.
if grep -qvE '^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$' "$TMP/v4" \
   || grep -qvE '^[0-9a-f:]+/[0-9]{1,3}$' "$TMP/v6" \
   || [ "$(wc -l < "$TMP/v4")" -lt 10 ] || [ "$(wc -l < "$TMP/v6")" -lt 5 ]; then
  echo "$(date -Is) refusing: unexpected content from cloudflare.com/ips-v4|v6"
  exit 1
fi
cat "$TMP/v4" "$TMP/v6" > "$TMP/all"
DAY=$(date +%F)

{
  echo "# Cloudflare proxies ascendpeptides.my and its subdomains. Trust CF-Connecting-IP"
  echo "# only from Cloudflare's own ranges, so \$remote_addr (logs, limit_req, the"
  echo "# X-Forwarded-For sent to the apps) is the real visitor."
  echo "# Generated by /usr/local/sbin/cloudflare-ips-refresh from cloudflare.com/ips-v4, /ips-v6."
  while read -r r; do echo "set_real_ip_from $r;"; done < "$TMP/all"
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP/realip.conf"

{
  echo "# Only Cloudflare (and this box) may reach the ascendpeptides.my vhosts directly."
  echo "# Uses \$realip_remote_addr, the TCP peer before CF-Connecting-IP is applied."
  echo "# Used by: if (\$from_cloudflare = 0) { return 444; } in sites-enabled/ascendpeptides.my"
  echo "# and sites-available/www-ascendpeptides."
  echo "# Generated by /usr/local/sbin/cloudflare-ips-refresh from cloudflare.com/ips-v4, /ips-v6."
  echo 'geo $realip_remote_addr $from_cloudflare {'
  echo "    default 0;"
  echo "    127.0.0.1/32 1;"
  echo "    ::1/128 1;"
  while read -r r; do echo "    $r 1;"; done < "$TMP/all"
  echo "}"
} > "$TMP/lock.conf"

# Compare only the ranges, so a header wording change doesn't trigger a reload.
ranges() { grep -oE '[0-9a-f.:]+/[0-9]+' "$1" | grep -vE '^(127\.0\.0\.1/32|::1/128)$' | sort; }
if [ "$(ranges "$REALIP")" = "$(ranges "$TMP/realip.conf")" ] && [ "$(ranges "$LOCK")" = "$(ranges "$TMP/lock.conf")" ]; then
  echo "$(date -Is) unchanged ($(wc -l < "$TMP/all") ranges)"
  exit 0
fi

cp "$REALIP" "$TMP/realip.bak"; cp "$LOCK" "$TMP/lock.bak"
install -m 644 "$TMP/realip.conf" "$REALIP"
install -m 644 "$TMP/lock.conf" "$LOCK"
if nginx -t >/dev/null 2>&1; then
  systemctl reload nginx
  echo "$(date -Is) updated to $(wc -l < "$TMP/all") ranges ($DAY), nginx reloaded"
else
  install -m 644 "$TMP/realip.bak" "$REALIP"; install -m 644 "$TMP/lock.bak" "$LOCK"
  echo "$(date -Is) nginx -t failed with new ranges; restored previous files"
  exit 1
fi
