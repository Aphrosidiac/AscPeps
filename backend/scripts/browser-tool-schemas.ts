// Regenerates src/modules/ai-agent/tools/browser.schemas.ts from the installed
// @playwright/mcp — the names, descriptions and input schemas of the browser
// tools Abby is offered. Run after upgrading the package:
//
//   npx tsx scripts/browser-tool-schemas.ts
//
// Checked in rather than read at boot so the API never loads Playwright until
// someone actually browses. test-agent-browser.ts fails when the snapshot and
// the package disagree.
import { writeFileSync } from 'node:fs';
import { createConnection } from '@playwright/mcp';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { BROWSER_TOOL_NAMES } from '../src/modules/ai-agent/tools/browser.allowlist.js';

export async function liveBrowserSchemas() {
  // Listing needs no browser: the endpoint is only dialled on the first call.
  const server = await createConnection({
    browser: { cdpEndpoint: 'http://127.0.0.1:9' },
    capabilities: ['core', 'core-navigation', 'core-tabs', 'core-input', 'vision'],
    codegen: 'none',
  });
  const [a, b] = InMemoryTransport.createLinkedPair();
  await server.connect(a);
  const client = new Client({ name: 'schemas', version: '1' });
  await client.connect(b);
  const { tools } = await client.listTools();
  await client.close();
  const byName = new Map(tools.map((t) => [t.name, t]));
  return BROWSER_TOOL_NAMES.map((name) => {
    const t = byName.get(name);
    if (!t) throw new Error(`@playwright/mcp no longer has ${name}`);
    const { $schema: _drop, ...input_schema } = t.inputSchema as Record<string, unknown>;
    return { name, description: t.description ?? '', input_schema };
  });
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const schemas = await liveBrowserSchemas();
  const version = (await import('@playwright/mcp/package.json', { with: { type: 'json' } })).default.version;
  writeFileSync(
    new URL('../src/modules/ai-agent/tools/browser.schemas.ts', import.meta.url),
    `// GENERATED by scripts/browser-tool-schemas.ts from @playwright/mcp ${version}. Do not edit.\n` +
      `export const PLAYWRIGHT_MCP_VERSION = ${JSON.stringify(version)};\n` +
      `export const BROWSER_SCHEMAS: { name: string; description: string; input_schema: Record<string, any> }[] = ${JSON.stringify(schemas, null, 2)};\n`
  );
  console.log(`wrote ${schemas.length} browser tool schemas (@playwright/mcp ${version})`);
  process.exit(0);
}
